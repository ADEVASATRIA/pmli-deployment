#!/usr/bin/env bash
# =============================================================================
# update-api.sh - interactive update of an already-deployed Laravel backend
# (API VM): fetch/pull -> pre-flight -> DB backup(s) -> migration plan ->
# maintenance window (composer, migrate per file, caches) -> PHP-FPM restart.
#
# Usage:  ./scripts/update-api.sh [APP_DIR] [--release FILE] [--backup-tables "a b"] [--swagger]
#         APP_DIR defaults to /var/www/pmli-backend.
#         Run as an admin user with sudo (or root); git/composer/artisan always
#         run as the OWNER of APP_DIR via `sudo -u <owner>`, never as root.
# Env:    PHP_VERSION=8.3   WEB_USER=www-data
#
# --release FILE   manifest (KEY="value": EXPECT_COMMIT, MIGRATIONS, BACKUP_TABLES,
#                  BACKUP_LEGACY_TABLES, MIN_UPLOAD_MB; optional: REQUIRE_PHP_EXT="zip ..."
#                  (checked in php -m CLI + FPM), REQUIRE_SCHEDULER="1" (schedule:run in
#                  a crontab / cron.d)), e.g. releases/2026-11-10/api.conf. The extra
#                  pre-flight checks only warn. CACHE_STORE=array/null in .env also warns.
#                  Only the migrations listed there are ever run (migrate --path=<file>);
#                  any other pending migration stops the update. Without --release,
#                  ANY pending migration stops the update (no automatic `migrate`).
# --backup-tables  overrides BACKUP_TABLES (empty = whole database).
#                  With --release and empty MIGRATIONS (and no --backup-tables), backups are skipped.
# --swagger        run l5-swagger:generate at the very end, non-fatal (skipped if absent).
#
# Differs from 03-deploy-app.sh: this one pulls code and, after you type y,
# migrates. Credentials are generated by PHP into a temporary 0600 defaults file
# (removed on exit); nothing secret is printed or placed on a command line.
# =============================================================================
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"

APP="/var/www/pmli-backend"; TABLES=""; TABLES_SET=0; RELEASE=""; SWAGGER=0
PHP_VERSION="${PHP_VERSION:-8.3}"; WEB_USER="${WEB_USER:-www-data}"
POS=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --backup-tables) [[ $# -ge 2 ]] || die "--backup-tables needs a value, e.g. \"users courses\""; TABLES="$2"; TABLES_SET=1; shift 2 ;;
    --release) [[ $# -ge 2 ]] || die "--release needs a manifest file"; RELEASE="$2"; shift 2 ;;
    --swagger) SWAGGER=1; shift ;;
    -h|--help) awk 'NR>1 && /^#/ {print; next} NR>1 {exit}' "${BASH_SOURCE[0]}"; exit 0 ;;
    -*) die "Unknown option: $1" ;;
    *) (( POS == 0 )) || die "Only one APP_DIR is accepted."; APP="${1%/}"; POS=1; shift ;;
  esac
done
[[ "${TABLES}" =~ ^[A-Za-z0-9_\ ]*$ ]] || die "--backup-tables may only contain table names (letters, digits, _) separated by spaces."

# --- Manifest ----------------------------------------------------------------
EXPECT_COMMIT=""; MIGRATIONS=""; BACKUP_TABLES=""; BACKUP_LEGACY_TABLES=""; MIN_UPLOAD_MB=""
REQUIRE_PHP_EXT=""; REQUIRE_SCHEDULER=""
if [[ -n "${RELEASE}" ]]; then
  unset EXPECT_COMMIT MIGRATIONS BACKUP_TABLES BACKUP_LEGACY_TABLES MIN_UPLOAD_MB REQUIRE_PHP_EXT REQUIRE_SCHEDULER
  load_env_file "${RELEASE}"
  EXPECT_COMMIT="${EXPECT_COMMIT:-}"; MIGRATIONS="${MIGRATIONS:-}"; BACKUP_TABLES="${BACKUP_TABLES:-}"
  BACKUP_LEGACY_TABLES="${BACKUP_LEGACY_TABLES:-}"; MIN_UPLOAD_MB="${MIN_UPLOAD_MB:-}"
  REQUIRE_PHP_EXT="${REQUIRE_PHP_EXT:-}"; REQUIRE_SCHEDULER="${REQUIRE_SCHEDULER:-}"
  for t in ${REQUIRE_PHP_EXT}; do [[ "${t}" =~ ^[A-Za-z0-9_]+$ ]] || die "Manifest: invalid PHP extension name '${t}'."; done
  [[ -z "${REQUIRE_SCHEDULER}" || "${REQUIRE_SCHEDULER}" =~ ^[01]$ ]] || die "Manifest: REQUIRE_SCHEDULER must be 0 or 1."
  [[ -z "${EXPECT_COMMIT}" || "${EXPECT_COMMIT}" =~ ^[0-9a-fA-F]{7,40}$ ]] || die "Manifest: EXPECT_COMMIT must be a 7-40 char hex commit id."
  [[ -z "${MIN_UPLOAD_MB}" || "${MIN_UPLOAD_MB}" =~ ^[0-9]+$ ]] || die "Manifest: MIN_UPLOAD_MB must be a number."
  for p in ${MIGRATIONS}; do
    [[ "${p}" =~ ^[A-Za-z0-9_./-]+\.php$ && "${p}" != *..* && "${p}" != /* ]] || die "Manifest: invalid migration path '${p}'."
  done
  for t in ${BACKUP_TABLES} ${BACKUP_LEGACY_TABLES}; do
    [[ "${t}" =~ ^[A-Za-z0-9_]+$ ]] || die "Manifest: invalid table name '${t}'."
  done
  log_ok "Manifest ${RELEASE}: commit=${EXPECT_COMMIT:-any}, $(wc -w <<<"${MIGRATIONS}") migration(s)"
fi
(( TABLES_SET )) || TABLES="${BACKUP_TABLES}"

for c in git composer php mysqldump curl sudo stat; do require_command "${c}"; done
[[ -d "${APP}" && -f "${APP}/artisan" && -f "${APP}/.env" ]] || die "${APP} is not a Laravel app (artisan/.env missing)."

OWNER="$(stat -c '%U' "${APP}")"
[[ "${OWNER}" != "root" ]] || die "${APP} is owned by root; artisan/composer must not run as root. chown it to the deploy/web user first."
if [[ "$(id -un)" == "${OWNER}" ]]; then run_as() { "$@"; }; else run_as() { sudo -H -u "${OWNER}" -- "$@"; }; fi
if [[ "$(id -u)" -eq 0 ]]; then priv() { "$@"; }; else priv() { sudo "$@"; }; fi
[[ "${OWNER}" == "${WEB_USER}" ]] || log_warn "Owner is '${OWNER}', not '${WEB_USER}': files artisan creates in storage/ must stay writable by ${WEB_USER} (shared group, or chown per scripts/03-deploy-app.sh)."

cd "${APP}"
ENV_TXT="$(run_as cat "${APP}/.env")" || die "Cannot read ${APP}/.env as ${OWNER}."
# envv KEY - value from .env; only used for the non-secret APP_URL.
envv() {
  local line val
  line="$(printf '%s\n' "${ENV_TXT}" | grep -E "^[[:space:]]*$1=" | tail -n 1 || true)"
  val="${line#*=}"; val="${val%$'\r'}"
  if [[ "${val}" =~ ^\"(.*)\"$ || "${val}" =~ ^\'(.*)\'$ ]]; then val="${BASH_REMATCH[1]}"; fi
  printf '%s' "${val}"
}
ask_yn() { # $1 = prompt ; returns 0 on y/Y, dies if no terminal
  local ans; [[ -t 0 ]] || die "Confirmation needed but no terminal available."
  read -r -p "$1 [y/N] " ans; [[ "${ans}" =~ ^[yY]$ ]]
}

# --- Cleanup: temp credentials + guaranteed `artisan up` ----------------------
MAINT=0; CNF=""
# fix_permissions - files artisan/composer created must stay usable by PHP-FPM
# (owner = deploy user, group = WEB_USER, group rwX, setgid dirs).
fix_permissions() {
  local d rc=0
  for d in "${APP}/storage" "${APP}/bootstrap/cache"; do
    [[ -d "${d}" ]] || continue
    priv chown -R "${OWNER}:${WEB_USER}" "${d}" || rc=1
    priv chmod -R ug+rwX "${d}" || rc=1
    priv find "${d}" -type d -exec chmod g+s {} + || rc=1
  done
  (( rc == 0 )) && log_ok "Permissions fixed (storage, bootstrap/cache: ${OWNER}:${WEB_USER}, ug+rwX, setgid dirs)." \
    || log_warn "fix_permissions had errors; check ownership of ${APP}/storage and ${APP}/bootstrap/cache."
  return "${rc}"
}
on_exit() {
  local rc=$?
  [[ -z "${CNF}" ]] || rm -f -- "${CNF}"
  if (( MAINT )); then
    fix_permissions || true
    log_warn "Exiting while in maintenance mode - attempting 'artisan up' ..."
    run_as php artisan up || log_error "FAILED to bring the app up. Run: cd ${APP} && sudo -u ${OWNER} php artisan up"
  fi
  if (( rc != 0 )); then log_error "Update aborted (exit ${rc}). Nothing after the failed step was run."; fi
}
trap on_exit EXIT

# --- 1. fetch, preview incoming commits, pull ---------------------------------
BEFORE="$(run_as git -C "${APP}" rev-parse --short HEAD)"
BRANCH="$(run_as git -C "${APP}" rev-parse --abbrev-ref HEAD)"
log_info "git fetch (branch ${BRANCH}) ..."
run_as git -C "${APP}" fetch
INCOMING="$(run_as git -C "${APP}" log --oneline 'HEAD..@{u}')" || die "Branch ${BRANCH} has no upstream; set one before updating."
if [[ -z "${INCOMING}" ]]; then
  log_info "No new commits upstream (HEAD ${BEFORE})."
else
  log_info "Commits that will be pulled:"; printf '%s\n' "${INCOMING}" | sed 's/^/    /'
  ask_yn "Pull these commits into ${APP}?" || die "Dibatalkan oleh operator. Tidak ada perubahan pada working tree."
  run_as git -C "${APP}" pull --ff-only
fi
AFTER="$(run_as git -C "${APP}" rev-parse --short HEAD)"
log_ok "Commit: ${BEFORE} -> ${AFTER}"
if [[ -n "${EXPECT_COMMIT}" ]]; then
  run_as git -C "${APP}" merge-base --is-ancestor "${EXPECT_COMMIT}" HEAD \
    || die "Expected commit ${EXPECT_COMMIT} is NOT contained in HEAD (${AFTER}). Stopping before composer/migrate."
  log_ok "HEAD contains expected commit ${EXPECT_COMMIT}."
fi

# --- 2. Pre-flight (warnings only) ---------------------------------------------
PREFLIGHT=""
pf() { PREFLIGHT="${PREFLIGHT}$1"$'\n'; log_info "pre-flight: $1"; }
pfw() { PREFLIGHT="${PREFLIGHT}WARN $1"$'\n'; log_warn "pre-flight: $1"; }
to_mb() { # 512M -> 512 ; 0/-1 -> unlimited (prints -1) ; unparsable -> -2
  local v="$1" n u
  [[ "${v}" == "0" || "${v}" == "-1" ]] && { echo -1; return; }
  [[ "${v}" =~ ^([0-9]+)([KkMmGg]?)$ ]] || { echo -2; return; }
  n="${BASH_REMATCH[1]}"; u="${BASH_REMATCH[2]}"
  case "${u}" in K|k) echo $((n / 1024));; M|m) echo "${n}";; G|g) echo $((n * 1024));; *) echo $((n / 1024 / 1024));; esac
}
if sudo -n -u "${WEB_USER}" true 2>/dev/null; then
  if sudo -n -u "${WEB_USER}" test -w "${APP}/storage/app"; then pf "storage/app writable by ${WEB_USER}: OK"; else pfw "storage/app NOT writable by ${WEB_USER}"; fi
else pfw "cannot sudo -n -u ${WEB_USER}; storage/app writability not checked"; fi
if [[ -n "${MIN_UPLOAD_MB}" ]]; then
  FPM_BIN="php-fpm${PHP_VERSION}"
  if command -v "${FPM_BIN}" >/dev/null 2>&1; then
    FPM_INFO="$("${FPM_BIN}" -i 2>/dev/null || true)"
    for k in upload_max_filesize post_max_size; do
      got="$(awk -F' => ' -v k="${k}" '$1==k {print $2; exit}' <<<"${FPM_INFO}")"; mb="$(to_mb "${got:-?}")"
      if [[ "${mb}" == "-1" ]] || { [[ "${mb}" =~ ^[0-9]+$ ]] && (( mb >= MIN_UPLOAD_MB )); }; then pf "FPM ${k}=${got} (>= ${MIN_UPLOAD_MB}M): OK"
      else pfw "FPM ${k}='${got:-?}' is below ${MIN_UPLOAD_MB}M"; fi
    done
  else pfw "${FPM_BIN} not found; FPM upload limits not checked"; fi
  API_SITES="$(grep -RlE '^[[:space:]]*fastcgi_pass' /etc/nginx/sites-enabled /etc/nginx/conf.d 2>/dev/null || true)"
  if [[ -z "${API_SITES}" ]]; then pfw "no Nginx site with fastcgi_pass found (or /etc/nginx unreadable); client_max_body_size not checked"
  else
    NGX="$(echo "${API_SITES}" | xargs grep -hE '^[[:space:]]*client_max_body_size' 2>/dev/null | sed -E 's/^[[:space:]]*client_max_body_size[[:space:]]+//; s/;.*//' | sort -u || true)"
    if [[ -z "${NGX}" ]]; then pfw "client_max_body_size not set in API Nginx site (default 1m) - uploads >= 1MB will get 413"
    else
      while read -r v; do
        mb="$(to_mb "${v}")"
        if [[ "${mb}" == "-1" ]] || { [[ "${mb}" =~ ^[0-9]+$ ]] && (( mb >= MIN_UPLOAD_MB )); }; then pf "Nginx client_max_body_size ${v} (>= ${MIN_UPLOAD_MB}M): OK"
        else pfw "Nginx client_max_body_size '${v}' is below ${MIN_UPLOAD_MB}M"; fi
      done <<<"${NGX}"
    fi
  fi
else log_info "pre-flight: MIN_UPLOAD_MB not set; upload limit checks skipped."; fi

# Optional manifest checks (warnings only)
if [[ -n "${REQUIRE_PHP_EXT}" ]]; then
  CLI_MODS="$(run_as php -m 2>/dev/null | tr 'A-Z' 'a-z' || true)"
  FPM_MODS="$(command -v "php-fpm${PHP_VERSION}" >/dev/null 2>&1 && "php-fpm${PHP_VERSION}" -m 2>/dev/null | tr 'A-Z' 'a-z' || true)"
  for t in ${REQUIRE_PHP_EXT}; do
    l="$(tr 'A-Z' 'a-z' <<<"${t}")"
    if grep -qx "${l}" <<<"${CLI_MODS}"; then pf "PHP ext ${t} (CLI): OK"; else pfw "PHP ext '${t}' missing in CLI (apt install php${PHP_VERSION}-${l})"; fi
    if [[ -z "${FPM_MODS}" ]]; then pfw "php-fpm${PHP_VERSION} -m unavailable; ext '${t}' not checked for FPM"
    elif grep -qx "${l}" <<<"${FPM_MODS}"; then pf "PHP ext ${t} (FPM): OK"
    else pfw "PHP ext '${t}' missing in FPM (apt install php${PHP_VERSION}-${l}; restart php${PHP_VERSION}-fpm)"; fi
  done
fi
if [[ "${REQUIRE_SCHEDULER}" == "1" ]]; then
  SCHED=""
  for u in "${OWNER}" "${WEB_USER}" root; do
    ct="$(sudo -n crontab -l -u "${u}" 2>/dev/null || true)"
    if grep -q 'schedule:run' <<<"${ct}"; then SCHED="crontab ${u}"; break; fi
  done
  if [[ -z "${SCHED}" ]] && grep -qsr 'schedule:run' /etc/cron.d 2>/dev/null; then SCHED="/etc/cron.d"; fi
  if [[ -n "${SCHED}" ]]; then pf "scheduler: schedule:run found (${SCHED}): OK"
  else pfw "scheduler: no 'schedule:run' in crontab of ${OWNER}/${WEB_USER}/root or /etc/cron.d (or sudo -n crontab not permitted)"; fi
fi
CACHE_STORE_VAL="$(envv CACHE_STORE | tr 'A-Z' 'a-z')"
case "${CACHE_STORE_VAL}" in
  array|null) pfw "CACHE_STORE=${CACHE_STORE_VAL} in .env: cache will not persist between requests (use file/redis/database)" ;;
  "") pf "CACHE_STORE not set in .env (config default applies)" ;;
  *) pf "CACHE_STORE=${CACHE_STORE_VAL}: OK" ;;
esac

# --- 3. DB backups (credentials generated by PHP -> temp 0600 file) -----------
# umask 077 is applied ONLY to the dump file (subshell below); it must not leak
# into artisan/composer (it once made bootstrap/cache 0600 -> HTTP 500).
install -d -m 0700 "${HOME}/backups"
DB_PHP='require "vendor/autoload.php"; $app = require "bootstrap/app.php";
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();
$n = ($argv[1] ?? "") !== "" ? $argv[1] : config("database.default");
$c = config("database.connections.$n");
if (!is_array($c)) { fwrite(STDERR, "CONNECTION_MISSING\n"); exit(3); }
if (!in_array($c["driver"] ?? "", ["mysql", "mariadb"], true)) { fwrite(STDERR, "DRIVER_UNSUPPORTED\n"); exit(4); }
$h = $c["host"] ?? "127.0.0.1"; if (is_array($h)) { $h = $h[0]; }
$q = fn($v) => "\"" . addcslashes((string) $v, "\\\"") . "\"";
echo "[client]\nuser=" . $q($c["username"] ?? "") . "\npassword=" . $q($c["password"] ?? "") . "\nhost=" . $q($h) . "\nport=" . (int) ($c["port"] ?? 3306) . "\n";
if (!empty($c["unix_socket"])) { echo "socket=" . $q($c["unix_socket"]) . "\n"; }
echo "#CONN=$n\n#DB=" . ($c["database"] ?? "") . "\n";'

# db_cnf CONNECTION - fill ${CNF} (0600) with a mysql defaults file for that Laravel
# connection ("" = default). Built by Laravel itself, so .env key names do not matter.
db_cnf() {
  local conn="$1" rc=0
  [[ -z "${CNF}" ]] || rm -f -- "${CNF}"
  CNF="$(mktemp)"; chmod 600 "${CNF}"
  run_as php -d display_errors=stderr -r "${DB_PHP}" "${conn}" > "${CNF}" || rc=$?
  case "${rc}" in
    0) ;;
    3) die "Database connection '${conn:-default}' is not defined in config/database.php." ;;
    4) die "Connection '${conn:-default}' is not a mysql/mariadb driver; backup not supported." ;;
    *) die "Could not read DB config from Laravel (exit ${rc}). The new code may need 'composer install' first; run it manually (composer install --no-dev) and retry." ;;
  esac
}

# backup_conn CONNECTION "TABLES" FILE_PREFIX -> sets LAST_BACKUP
LAST_BACKUP=""
backup_conn() {
  local conn="$1" tables="$2" prefix="$3" dbn engines="" t
  db_cnf "${conn}"
  dbn="$(sed -n 's/^#DB=//p' "${CNF}")"
  [[ "${dbn}" =~ ^[A-Za-z0-9_]+$ ]] || die "Unexpected database name for connection '${conn:-default}'."
  LAST_BACKUP="${HOME}/backups/${prefix}${dbn}-$(timestamp).sql"
  local extra=()
  if command -v mysql >/dev/null 2>&1; then
    local where="TABLE_SCHEMA='${dbn}'"
    if [[ -n "${tables}" ]]; then where="${where} AND TABLE_NAME IN ($(printf "'%s'," ${tables} | sed 's/,$//'))"; fi
    engines="$(mysql --defaults-extra-file="${CNF}" -N -e "SELECT DISTINCT ENGINE FROM information_schema.TABLES WHERE ${where}" 2>/dev/null || true)"
    if grep -qix 'MyISAM' <<<"${engines}"; then
      log_warn "MyISAM tables in this dump: --single-transaction cannot make MyISAM consistent. Dump is NOT transactionally consistent; avoid writes during the backup."
      extra+=(--lock-tables=false)
    fi
  else log_warn "mysql client not found; engine check skipped."; fi
  if [[ -n "${tables}" ]]; then log_info "Backing up [${tables}] from '${dbn}' (connection ${conn:-default}) ..."; else log_warn "No table list: dumping the WHOLE database '${dbn}' (connection ${conn:-default})."; fi
  # shellcheck disable=SC2086  # tables are validated and intentionally word-split
  ( umask 077; mysqldump --defaults-extra-file="${CNF}" --single-transaction --no-tablespaces ${extra[@]+"${extra[@]}"} "${dbn}" ${tables} > "${LAST_BACKUP}" )
  rm -f -- "${CNF}"; CNF=""
  [[ -s "${LAST_BACKUP}" ]] || die "Backup file is empty: ${LAST_BACKUP}"
  chmod 600 "${LAST_BACKUP}"
  log_ok "Backup written: ${LAST_BACKUP} ($(du -h "${LAST_BACKUP}" | cut -f1))"
}

if [[ -n "${RELEASE}" && -z "${MIGRATIONS//[[:space:]]/}" ]] && (( ! TABLES_SET )); then
  log_info "Tidak ada migration di manifest; backup dilewati."
  BACKUP="skipped (no migrations)"; BACKUP_LEGACY="skipped (no migrations)"
else
  backup_conn "" "${TABLES}" ""; BACKUP="${LAST_BACKUP}"
  BACKUP_LEGACY="not requested"
  if [[ -n "${BACKUP_LEGACY_TABLES}" ]]; then backup_conn "legacy" "${BACKUP_LEGACY_TABLES}" "legacy-"; BACKUP_LEGACY="${LAST_BACKUP}"; fi
fi

# --- 4. Migration plan (only manifest migrations, always via --path) -----------
STATUS="$(run_as php artisan migrate:status --no-ansi)" || die "migrate:status failed (DB connection? new code may need composer install)."
RAN_NAMES="$(printf '%s\n' "${STATUS}" | awk '$NF=="Ran" {print $1}')"
PENDING_NAMES="$(printf '%s\n' "${STATUS}" | awk '$NF=="Pending" {print $1}')"
QUEUE=""; SKIPPED=""; LISTED=""
for p in ${MIGRATIONS}; do
  [[ -f "${APP}/${p}" ]] || die "Migration file not found in repo: ${p}"
  n="$(basename "${p}" .php)"; LISTED="${LISTED}${n}"$'\n'
  if grep -Fxq -- "${n}" <<<"${RAN_NAMES}"; then SKIPPED="${SKIPPED}${n}"$'\n'; log_info "SKIP (already Ran): ${n}"
  elif grep -Fxq -- "${n}" <<<"${PENDING_NAMES}"; then QUEUE="${QUEUE}${p}"$'\n'; log_info "QUEUE (Pending): ${n}"
  else die "Migration '${n}' is in the manifest but unknown to migrate:status (module disabled / not registered?). Stopping."; fi
done
OTHER=""
while read -r n; do
  [[ -n "${n}" ]] || continue
  grep -Fxq -- "${n}" <<<"${LISTED}" || OTHER="${OTHER}${n}"$'\n'
done <<<"${PENDING_NAMES}"
if [[ -n "${OTHER}" ]]; then
  log_error "Pending migrations NOT covered by the manifest:"; printf '%s' "${OTHER}" | sed 's/^/    /' >&2
  die "Add them to the manifest MIGRATIONS (release file) or run them manually. This script never runs an unscoped 'migrate'."
fi
if [[ -n "${QUEUE}" ]]; then
  while read -r p; do
    [[ -n "${p}" ]] || continue
    log_info "migrate --pretend: ${p}"
    run_as php artisan migrate --pretend --path="${p}" --force --no-ansi
  done <<<"${QUEUE}"
  log_warn "Backups: default=${BACKUP}  legacy=${BACKUP_LEGACY}"
  ask_yn "Jalankan $(printf '%s' "${QUEUE}" | grep -c .) migration di atas pada database ini?" || die "Dibatalkan oleh operator. Kode sudah ter-pull (${AFTER}); database TIDAK diubah."
else
  log_ok "No migrations to run."
fi

# --- 5. Maintenance window -------------------------------------------------------
run_as php artisan down --retry=60
MAINT=1
log_info "Maintenance mode enabled."
log_info "composer install --no-dev --optimize-autoloader ..."
run_as composer install --no-dev --prefer-dist --optimize-autoloader --no-interaction

DONE=""
if [[ -n "${QUEUE}" ]]; then
  while read -r p; do
    [[ -n "${p}" ]] || continue
    log_info "migrate --path=${p}"
    if run_as php artisan migrate --path="${p}" --force --no-ansi; then DONE="${DONE}${p}"$'\n'; log_ok "Migrated: ${p}"
    else
      log_error "Migration FAILED: ${p}"
      log_error "Already run:"; printf '%s' "${DONE:-    (none)}" | sed 's/^/    /' >&2
      log_error "Not run:"; printf '%s' "${QUEUE}" | grep -Fxv -e "${p}" -f <(printf '%s' "${DONE}") | sed 's/^/    /' >&2 || true
      die "Stopped at the failed migration; artisan up will be attempted. Restore from ${BACKUP} if the schema is inconsistent."
    fi
  done <<<"${QUEUE}"
fi
run_as php artisan optimize:clear
run_as php artisan config:cache
run_as php artisan route:cache
run_as php artisan event:cache || log_warn "event:cache gagal (non-fatal); app tetap dinaikkan."
fix_permissions || true
run_as php artisan up
MAINT=0
log_ok "Maintenance mode disabled."
PERM_STATUS="not checked (cannot sudo -n -u ${WEB_USER})"
if sudo -n -u "${WEB_USER}" true 2>/dev/null; then
  if sudo -n -u "${WEB_USER}" test -r "${APP}/bootstrap/cache/config.php"; then PERM_STATUS="OK"
  else
    log_error "${WEB_USER} cannot read ${APP}/bootstrap/cache/config.php - PHP-FPM would answer HTTP 500. Re-running fix_permissions ..."
    fix_permissions || true
    if sudo -n -u "${WEB_USER}" test -r "${APP}/bootstrap/cache/config.php"; then PERM_STATUS="repaired"; else PERM_STATUS="FAILED"; log_error "Still unreadable by ${WEB_USER}: fix ownership/modes of bootstrap/cache manually."; fi
  fi
fi
run_as php artisan queue:restart || log_warn "queue:restart gagal (non-fatal); jalankan manual."

# --- 6. PHP-FPM --------------------------------------------------------------------
priv systemctl restart "php${PHP_VERSION}-fpm"
sleep 2
priv systemctl is-active --quiet "php${PHP_VERSION}-fpm" || die "php${PHP_VERSION}-fpm is not active after restart."
log_ok "php${PHP_VERSION}-fpm restarted."


# --- 6b. Swagger (optional, non-fatal, after the app is live) --------------------
SWAGGER_STATUS="not requested"
if (( SWAGGER )); then
  CMDS="$(run_as php artisan list --raw 2>/dev/null || true)"
  if grep -q '^l5-swagger:generate' <<<"${CMDS}"; then
    if SW_OUT="$(run_as php artisan l5-swagger:generate 2>&1)"; then SWAGGER_STATUS="generated"; log_ok "Swagger generated."
    else SWAGGER_STATUS="FAILED (deploy tetap berhasil)"; log_warn "Swagger gagal di-generate (deploy tetap berhasil)"; tail -n 3 <<<"${SW_OUT}" | sed 's/^/    /' >&2; fi
  else SWAGGER_STATUS="skipped (command not found)"; log_warn "--swagger given but l5-swagger:generate does not exist; skipped."; fi
fi
# --- 7. Summary --------------------------------------------------------------------
BASE="$(envv APP_URL)"; BASE="${BASE%/}"
probe() { curl -s -o /dev/null -w '%{http_code}' --max-time 10 "${BASE}$1" 2>/dev/null || echo 000; }
